// Robolectric starts an Android image before its first test. On CI (#169, run 45022042624) the
// app's test task took 13 to 21 s with it, and the timed run went to 51.5 s against a budget of
// 30. The measured test time (scripts/levels.py) leaves those tests out when it passes
// -PcvLeaveOutRobolectric (#169). No test run has a time cap; each run logs its time, as a
// measure only, and a test that waits bounds its own wait.
tasks.withType<Test>().configureEach {
    if (providers.gradleProperty("cvLeaveOutRobolectric").isPresent) {
        filter.excludeTestsMatching("org.claudevoice.mobile.app.robolectric.*")
    }
    addTestListener(object : TestListener {
        override fun beforeSuite(suite: TestDescriptor) = Unit
        override fun beforeTest(testDescriptor: TestDescriptor) = Unit
        override fun afterTest(testDescriptor: TestDescriptor, result: TestResult) = Unit
        override fun afterSuite(suite: TestDescriptor, result: TestResult) {
            if (suite.parent == null) logger.lifecycle("$path took ${result.endTime - result.startTime} ms")
        }
    })
}

// NoBackupTest reads the manifest the build merged for the variant under test, and the rules
// file it names, so what it checks is what ships. MergedPermissionsTest reads where each
// permission in it came from.
androidComponents {
    onVariants { variant ->
        val name = variant.name.replaceFirstChar { it.uppercase() }
        val manifest = layout.buildDirectory
            .file("intermediates/merged_manifest/${variant.name}/process${name}MainManifest/AndroidManifest.xml")
        // The merger's record of which module each line came from; MergedPermissionsTest reads it.
        val record = layout.buildDirectory.file("outputs/logs/manifest-merger-${variant.name}-report.txt")
        tasks.matching { it.name == "test${name}UnitTest" }.configureEach {
            dependsOn("process${name}MainManifest")
            // Declared as inputs, so a change to any runs the test again instead of reusing it.
            inputs.file(manifest)
            inputs.file(record)
            inputs.dir("src/main/res/xml")
            (this as Test).systemProperty("mergedManifest", manifest.get().asFile.path)
            systemProperty("mergerReport", record.get().asFile.path)
            systemProperty("resources", file("src/main/res").path)
        }
    }
}

// The plugins -PcvPlugins picked (ADR-CVM-007): each is a dependency, and the app's list of them is
// generated, so no code names a plugin that was left out of the build.
@Suppress("UNCHECKED_CAST")
val pickedPlugins = gradle.extensions.extraProperties["cvPlugins"] as List<String>

abstract class BuiltPlugins : DefaultTask() {
    @get:Input
    abstract val picked: ListProperty<String>

    @get:OutputDirectory
    abstract val out: DirectoryProperty

    @TaskAction
    fun write() {
        val file = out.get().file("org/claudevoice/mobile/app/BuiltPlugins.kt").asFile
        file.parentFile.mkdirs()
        val entries = picked.get().joinToString("\n") { "    \"$it\" to org.claudevoice.mobile.plugins.$it.Entry::plugin," }
        file.writeText(
            "// Generated by :app:builtPlugins from -PcvPlugins. Do not edit.\n" +
                "package org.claudevoice.mobile.app\n\n" +
                "import android.content.Context\n" +
                "import org.claudevoice.mobile.pluginapi.Plugin\n\n" +
                "/** Each plugin this build takes, by its folder's name, and how to build it. */\n" +
                "internal val BUILT_PLUGINS: List<Pair<String, (Context) -> Plugin>> = listOf(\n" +
                entries + "\n)\n",
        )
    }
}

val builtPlugins = tasks.register<BuiltPlugins>("builtPlugins") {
    description = "Writes the list of the plugins this build takes, from -PcvPlugins."
    picked.set(pickedPlugins)
}

androidComponents {
    onVariants { variant -> variant.sources.java?.addGeneratedSourceDirectory(builtPlugins, BuiltPlugins::out) }
}

// ADR-CVM-007: the merged manifest asks only for what the app or a module this build took declares.
// The modules are every project in the build, which settings limits to the fixed ones and the
// plugins -PcvPlugins picked; CI runs this on the default list and on `all`.
abstract class CheckMergedManifest : DefaultTask() {
    @get:InputFile
    @get:PathSensitive(PathSensitivity.NONE)
    abstract val merged: RegularFileProperty

    @get:InputFiles
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val declared: ConfigurableFileCollection

    // Fills `${applicationId}` in the declared manifests, as the merge does in the merged one.
    @get:Input
    abstract val applicationId: Property<String>

    @get:OutputFile
    abstract val report: RegularFileProperty

    @TaskAction
    fun check() {
        val found = ManifestCheck.undeclared(
            ManifestEntries.of(merged.get().asFile.readText()),
            declared.files.map { ManifestEntries.of(it.readText(), applicationId.get()) },
        )
        report.get().asFile.writeText(found.joinToString("\n", postfix = "\n"))
        if (found.isNotEmpty()) throw GradleException(found.joinToString("\n"))
    }
}

androidComponents {
    onVariants { variant ->
        val name = variant.name.replaceFirstChar { it.uppercase() }
        val task = tasks.register<CheckMergedManifest>("check${name}MergedManifest") {
            description = "Fails when the merged manifest asks for what no module this build took declares."
            merged.set(variant.artifacts.get(com.android.build.api.artifact.SingleArtifact.MERGED_MANIFEST))
            declared.from(rootProject.subprojects.map { it.file("src/main/AndroidManifest.xml") }.filter { it.isFile })
            applicationId.set(variant.applicationId)
            report.set(layout.buildDirectory.file("reports/manifest/${variant.name}.txt"))
        }
        tasks.named("check") { dependsOn(task) }
    }
}

